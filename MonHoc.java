public class MonHoc {
    private String ma, ten;
    private int soTin;

    public MonHoc(String ma, String ten, int soTin) {
        this.ma = ma;
        this.ten = ten;
        this.soTin = soTin;
    }

    public String getMa() {
        return ma;
    }

    public String getTen() {
        return ten;
    }
}